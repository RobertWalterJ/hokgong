// Fold the app into one HTML file for the phone.
//
//   node build/single.mjs
//
// Runs the gates first — verify, the verifier's own self-test, the colour
// audit and the scheduler simulation — and any failure stops the build. Then
// the modules are bundled into one script, the Latin fonts are inlined, and
// the deck is inlined so nothing is fetched.
//
// The recordings are NOT inlined: 545 mp3s come to 16 MB, which as base64
// would be 21 MB — past what an Artifact will take. This page points at
// audio.tatoeba.org instead, and build/make-deploy.mjs switches it to the
// local folder for the installable version. Where neither is reachable the
// app finds out at startup and sets the listening questions aside.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const APP = join(ROOT, 'app');
const run = (f) => execFileSync(process.execPath, [join(ROOT, 'build', f)], { stdio: 'inherit' });
run('verify.mjs');
run('test-verify.mjs');
run('audit-colour.mjs');
execFileSync(process.execPath, [join(ROOT, 'audits', 'run-dyslexia.mjs')], { stdio: 'inherit' });
run('test-schedule.mjs');

const js = (await build({
  entryPoints: [join(APP, 'js', 'app.js')], bundle: true, format: 'iife', write: false,
  minify: true, target: 'es2020', legalComments: 'none',
})).outputFiles[0].text;

const fonts = readFileSync(join(APP, 'fonts', 'fonts.css'), 'utf8')
  .split('\n').filter((l) => !/vietnamese/.test(l)).join('\n')
  .replace(/url\((([\w-]+)\.woff2)\)/g, (_, file) =>
    `url(data:font/woff2;base64,${readFileSync(join(APP, 'fonts', file)).toString('base64')})`);

// Function replacers throughout: a replacement STRING treats `$&`, `$'` and
// `` $` `` specially, and minified code or a dictionary gloss can contain them.
const safe = (s) => s.replace(/<\/script/gi, '<\\/script');
const deck = safe(readFileSync(join(APP, 'data', 'deck.json'), 'utf8'));

// The version shown in About: the package number, the commit it was built
// from (with "+" if anything was uncommitted — app/data is generated by this
// build, so it does not count), and the local calendar date.
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
let commit = 'local';
try {
  commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT }).toString().trim();
  if (execFileSync('git', ['status', '--porcelain', '--', 'app', 'content', 'build', ':!app/data'], { cwd: ROOT }).toString().trim()) commit += '+';
} catch { /* not a repo */ }
const d = new Date();
const BUILD = JSON.stringify({ v: pkg.version, commit, date: `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}` });

const html = readFileSync(join(APP, 'index.html'), 'utf8')
  .replace('<link rel="stylesheet" href="fonts/fonts.css">', () => `<style>${fonts}</style>`)
  .replace('<script type="module" src="js/app.js"></script>', () =>
    `<script>window.HOKGONG_BUILD=${BUILD};window.HOKGONG_AUDIO="https://audio.tatoeba.org/sentences/yue/";window.HOKGONG_DECK=${deck};</script>\n<script>${safe(js)}</script>`);
if (html.includes('js/app.js')) throw new Error('the module script tag was not replaced');

mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, 'dist', 'hokgong.html'), html);
console.log(`wrote dist/hokgong.html — ${(html.length / 1024 / 1024).toFixed(1)} MB`);
